"""Offline check of the machine gun pack (T-272), outside Unreal and outside Blender: files and sha256 of the manifest,
FBX units (UnitScaleFactor 100 = metres), skin clusters in the skeletal FBX, every clip in both views with the same
length and events, the contract events with T-273 (Fire x4 + CrankTick per FireLoop turn, the seven reload events in
order, SteamVent, Empty / Release...), the bones and sockets in the base FBX, the textures listed by label (sizes,
colour spaces), fp-framing.json, the belt margins and the statics. Writes <pack>/machinegun-clips.inl.txt (the
FFirearmClip::Make table in the format of scripts/character/pirate_weapon_clips.py).

  python scripts/props/machinegun_pack/check_pack.py [build/packs/bean-machinegun]
Exit 1 when something is wrong.
"""
from __future__ import annotations

import hashlib
import json
import os
import struct
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
CLIPS = {'Equip': 54, 'Idle': 90, 'Walk': 120, 'Sprint': 90, 'FireStart': 17, 'FireLoop': 16, 'FireEnd': 10, 'Reload': 150,
         'Overheat': 60, 'Inspect': 180, 'Holster': 48, 'DryFire': 14, 'Discard': 40}
LOOPS = {'Idle', 'Walk', 'Sprint', 'FireLoop'}
EXPECTED_EVENTS = {
    'FireStart': [(0, 'CrankTick'), (1, 'Fire'), (9, 'Fire'), (13, 'Fire')],
    'FireLoop': [(0, 'CrankTick'), (0, 'Fire'), (4, 'Fire'), (8, 'Fire'), (12, 'Fire')],
    'FireEnd': [(8, 'CrankTick')],
    'Reload': [(16, 'CoverOpen'), (34, 'BeltOut'), (64, 'BoxOut'), (92, 'BoxIn'), (116, 'BeltIn'), (126, 'CoverClose'), (136, 'Charge')],
    'Overheat': [(6, 'SteamVent')],
    'Equip': [(6, 'DrawWeapon'), (46, 'Ready')],
    'Holster': [(42, 'StowWeapon')],
    'DryFire': [(4, 'DryClick')],
    'Discard': [(4, 'Empty'), (24, 'Release')],
}
REQUIRED_BONES = ['gun_root', 'jacket', 'crank', 'feed_cover', 'cocking_handle', 'steam_cap', 'ammo_box', 'tripod', 'belt_01', 'belt_17',
                  'belt_out_01', 'belt_out_10', 'socket_grip_r', 'socket_grip_l', 'socket_grip_l_tp', 'socket_muzzle', 'socket_eject',
                  'socket_eject_dir', 'socket_steam', 'socket_jacket', 'socket_hose', 'socket_feed', 'socket_belt_out', 'socket_box',
                  'socket_box_slot', 'socket_cocking', 'socket_cover_latch', 'socket_crank_handle']
STATICS = ['SM_Bean_MachineGun', 'SM_Ammo_MGBox', 'SM_MG_Casing', 'SM_MG_BeltLink']
MATERIALS = {'M_MG_Body': 2048, 'M_MG_Jacket': 2048, 'M_MG_Belt': 1024, 'M_MG_Box': 1024, 'M_MG_Casing': 512}


def fbx_unit(path):
    data = open(path, 'rb').read()
    i = data.find(b'UnitScaleFactor')
    if i < 0:
        return None
    j = data.find(b'D', data.find(b'Number', i))
    return struct.unpack('<d', data[j + 1:j + 9])[0]


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def png_size(path):
    with open(path, 'rb') as f:
        head = f.read(24)
    if head[:8] != b'\x89PNG\r\n\x1a\n':
        return None
    return struct.unpack('>II', head[16:24])


def clip_table(m):
    by_view = {}
    for scene in m['scenes']:
        events = [(e['frame'] - scene['start'], e['name']) for e in scene['events']]
        by_view[(scene['view'], scene['clip'])] = (scene['end'] - scene['start'], scene['fps'], events)
    lines = [f"\t/** {m['format']} v{m['version']} ({m.get('pack')}): {len(by_view) // 2} gestures, generated by "
             f"scripts/props/machinegun_pack/check_pack.py */", "\tinline void AddMachineGunClips(TArray<FFirearmClip>& Out)", "\t{"]
    for (view, clip), (frames, fps, events) in by_view.items():
        if view != 'TP':
            continue
        loop = 'true' if clip in LOOPS else 'false'
        ev = ', '.join(f'{{ TEXT("{name}"), {frame} }}' for frame, name in events)
        lines.append(f"\t\tOut.Add(FFirearmClip::Make(EFirearmGesture::{clip}, {frames}, {fps}, {loop}, {{ {ev} }}));"
                     if ev else f"\t\tOut.Add(FFirearmClip::Make(EFirearmGesture::{clip}, {frames}, {fps}, {loop}, {{}}));")
    lines.append("\t}")
    return '\n'.join(lines) + '\n'


def check(pack):
    m = json.load(open(os.path.join(pack, 'machinegun-manifest.json'), encoding='utf-8'))
    errors, warnings = [], []
    report = {'pack': pack, 'format': f"{m['format']} v{m['version']}", 'fps': m['fps'], 'units': {}, 'clips': {}, 'assets': len(m['assets'])}
    if m['fps'] != 30:
        errors.append(f'fps {m["fps"]} (expected 30)')
    sizes = 0
    for entry in m['assets']:
        path = os.path.join(pack, entry['path'])
        if not os.path.isfile(path):
            errors.append(f'missing {entry["path"]}')
            continue
        sizes += os.path.getsize(path)
        if entry.get('sha256') and sha256(path) != entry['sha256']:
            errors.append(f'sha256 mismatch {entry["path"]}')
        if path.endswith('.fbx'):
            unit = fbx_unit(path)
            report['units'][str(unit)] = report['units'].get(str(unit), 0) + 1
    report['exports_mb'] = round(sizes / 1e6, 1)
    if set(report['units']) - {'100.0'}:
        errors.append(f'FBX units {report["units"]} (expected UnitScaleFactor 100 everywhere: metres)')
    scenes = {(s['view'], s['clip']): s for s in m['scenes']}
    for clip, frames in CLIPS.items():
        for view in ('TP', 'FP'):
            if (view, clip) not in scenes:
                errors.append(f'clip {view} {clip} missing')
        tp, fp = scenes.get(('TP', clip)), scenes.get(('FP', clip))
        if not tp or not fp:
            continue
        if tp['end'] != frames:
            errors.append(f'clip {clip}: {tp["end"]} frames (expected {frames})')
        a = (tp['end'], sorted((e['frame'], e['name']) for e in tp['events']))
        b = (fp['end'], sorted((e['frame'], e['name']) for e in fp['events']))
        if a != b:
            errors.append(f'clip {clip}: TP and FP differ (length or events)')
        got = sorted((e['frame'], e['name']) for e in tp['events'])
        if clip in EXPECTED_EVENTS and got != sorted(EXPECTED_EVENTS[clip]):
            errors.append(f'clip {clip}: events {got} (contract {sorted(EXPECTED_EVENTS[clip])})')
        report['clips'][clip] = {'frames': tp['end'], 'seconds': round(tp['end'] / m['fps'], 3), 'loop': clip in LOOPS, 'events': got,
                                 'tp_hand_error_m': {k: round(v, 3) for k, v in tp['qa']['hand_error_max_m'].items()},
                                 'tp_arm_stretch_max': round(tp['qa']['upperarm_scale_max'], 3)}
        if max(tp['qa']['hand_error_max_m'].values()) > 0.08:
            warnings.append(f'TP {clip}: a hand misses its target by {max(tp["qa"]["hand_error_max_m"].values()):.3f} m (short bean arms)')
        if max(fp['qa']['hand_error_max_m'].values()) > 0.002:
            errors.append(f'FP {clip}: hand error {fp["qa"]["hand_error_max_m"]}')
    anims = [a for a in m['assets'] if a['type'] == 'animation']
    bean = sum(1 for a in anims if a['skeleton_group'] == 'Bean')
    report['animation_fbx'] = {'bean': bean, 'weapon': len(anims) - bean}
    if bean != len(CLIPS) * 2 or len(anims) - bean != len(CLIPS) * 2:
        errors.append(f'animation FBX: {bean} bean / {len(anims) - bean} weapon (expected {len(CLIPS) * 2} each)')
    # bases: the weapon (own skeleton, every bone and socket, skinned) and the two bean bases
    base = next((a for a in m['assets'] if a['type'] == 'skeletal_mesh' and a['skeleton_group'] == 'MachineGun'), None)
    if base:
        data = open(os.path.join(pack, base['path']), 'rb').read()
        missing = [b for b in REQUIRED_BONES + m['weapon_contract']['bones'] if data.find(b.encode()) < 0]
        if missing:
            errors.append(f'base FBX lacks bones {sorted(set(missing))}')
        clusters = data.count(b'Cluster')
        report['weapon_base'] = {'path': base['path'], 'bones': len(m['weapon_contract']['bones']), 'skin_clusters_in_fbx': clusters,
                                 'triangles': m['weapon_contract']['triangle_count'],
                                 'size_cm': [round(v * 100, 1) for v in m['weapon_contract']['bounds']['size']]}
        if clusters == 0:
            errors.append('weapon base FBX has no skin cluster')
    else:
        errors.append('no weapon base FBX')
    for view in ('TP', 'FP'):
        if not any(a['type'] == 'skeletal_mesh' and a['skeleton_group'] == 'Bean' and a.get('view') == view for a in m['assets']):
            errors.append(f'bean base {view} missing')
    # statics
    st = {os.path.splitext(os.path.basename(a['path']))[0]: a for a in m['assets'] if a['type'] == 'static_mesh' and a['path'].endswith('.fbx')}
    for name in STATICS:
        if name not in st:
            errors.append(f'static {name} missing')
    pickups = [n for n, a in st.items() if a.get('view') == 'pickup']
    if pickups != ['SM_Bean_MachineGun']:
        errors.append(f'pickup statics {pickups} (expected only SM_Bean_MachineGun)')
    report['statics'] = {n: {'view': a.get('view'), 'size_m': a.get('size_m'), 'triangles': a.get('triangles'), 'collision': a.get('collision'),
                             'materials': a.get('material')} for n, a in st.items()}
    casing = st.get('SM_MG_Casing', {}).get('size_m')
    if casing and not (0.050 <= casing[0] <= 0.062):
        errors.append(f'SM_MG_Casing length {casing[0]} m (expected ~0.056)')
    # textures by label
    tex = {}
    for mat, size in MATERIALS.items():
        data = (m.get('materials') or {}).get(mat)
        if not data:
            errors.append(f'material {mat} missing from manifest.materials')
            continue
        tex[mat] = {}
        for label, cs in (('BaseColor', 'sRGB'), ('Normal', 'Non-Color'), ('ORM', 'Non-Color')):
            info = data['textures'].get(label)
            if not info:
                errors.append(f'{mat}: texture {label} missing')
                continue
            path = os.path.join(pack, info['path'])
            got = png_size(path) if os.path.isfile(path) else None
            tex[mat][label] = {'path': info['path'], 'size': got, 'colorspace': info.get('colorspace')}
            if got != (size, size):
                errors.append(f'{mat} {label}: size {got} (expected {size})')
            if info.get('colorspace') != cs:
                errors.append(f'{mat} {label}: colour space {info.get("colorspace")} (expected {cs})')
    heat = ((m.get('materials') or {}).get('M_MG_Jacket') or {}).get('textures', {}).get('Heat')
    if not heat or not os.path.isfile(os.path.join(pack, heat['path'])):
        errors.append('M_MG_Jacket: heat mask (label Heat) missing')
    else:
        tex['M_MG_Jacket']['Heat'] = {'path': heat['path'], 'size': png_size(os.path.join(pack, heat['path']))}
    report['textures'] = tex
    # framing, belt
    framing_file = os.path.join(pack, 'fp-framing.json')
    if not os.path.isfile(framing_file):
        errors.append('fp-framing.json missing')
    else:
        fr = json.load(open(framing_file, encoding='utf-8'))
        report['fp_framing'] = {k: fr.get(k) for k in ('hip_grip_location_cm', 'hip_rotation_pyr_deg', 'muzzle_in_view_cm', 'grip_socket')}
        if 'aim_muzzle_location_cm' in fr:
            warnings.append('fp-framing.json has an aim pose: the machine gun is not aimed')
    belt = m.get('belt_check', {})
    report['belt_check'] = belt
    for k in ('in_below_slot_at_4p_m', 'out_inside_pouch_at_4p_m', 'spare_out_reaches_extract_at_4p_m'):
        if belt.get(k, -1) <= 0:
            errors.append(f'belt margin {k} = {belt.get(k)} (a pocket would show past its hidden end)')
    with open(os.path.join(pack, 'machinegun-clips.inl.txt'), 'w', encoding='utf-8', newline='') as f:
        f.write(clip_table(m).replace('\n', '\r\n'))
    report['errors'], report['warnings'] = errors, warnings
    print(json.dumps(report, indent=1, ensure_ascii=False))
    print('MachineGun: ' + ('CHECK OK' if not errors else 'CHECK FAILED'))
    return not errors


if __name__ == '__main__':
    pack = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'build', 'packs', 'bean-machinegun')
    sys.exit(0 if check(pack) else 1)
