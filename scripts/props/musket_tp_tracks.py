"""Generates Weapons/MusketThirdPersonTracks.inl: the musket relative to Bean's hand_r, frame by frame.

In the maquette bean-musket-anim (second PC) the musket is its own object: during the reload the right hand
lets go of it (flask, cartridge, ramrod) and the left hand holds it by the barrel. Welded to hand_r in Unreal it
flew with the right hand; these tracks put it back where the animation has it.

Usage (Blender in the background, the maquette .blend is only read):
  blender -b <OneDrive>/maquette-blender/maquettes/bean-musket-anim/bean-musket-anim.blend \
      --python scripts/props/musket_tp_tracks.py
Same frame ranges and same hand_r -> socket grip_r convention as exports/attach_tp.json (export_ue.py).
"""
import math
import pathlib

import bpy
from mathutils import Vector

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "monke_island/Source/monke_island/Weapons/MusketThirdPersonTracks.inl"
FPS = 24


def F(t):
    return int(round(1 + t * FPS))


scene = bpy.context.scene
bean = bpy.data.objects["SKEL_Bean"]
musket = next(o for o in bpy.data.objects if o.type == "ARMATURE" and "socket_grip_r" in o.data.bones)


def idle_start():
    # timeline.json frames_by_phase["idle"][0] (export_ue.py RANGES["Hold"])
    import json
    tl = pathlib.Path(bpy.data.filepath).parent / "timeline.json"
    return json.loads(tl.read_text(encoding="utf-8"))["frames_by_phase"]["idle"][0]


RANGES = {
    "Reload": (F(0.0), F(6.6)),
    "Fire": (F(6.6), F(7.6)),
    "Hold": (idle_start(), idle_start() + FPS),
}


def rotator(X, Y, Z):
    pitch = math.atan2(X.z, math.hypot(X.x, X.y))
    yaw = math.atan2(X.y, X.x)
    sy_axis = Vector((-math.sin(yaw), math.cos(yaw), 0.0))
    roll = math.atan2(Z.dot(sy_axis), Y.dot(sy_axis))
    return math.degrees(pitch), math.degrees(yaw), math.degrees(roll)


def relative(frame):
    scene.frame_set(frame)
    H = bean.matrix_world @ bean.pose.bones["hand_r"].matrix
    Mg = musket.matrix_world @ musket.pose.bones["socket_grip_r"].matrix
    rel = H.inverted() @ Mg
    t = rel.translation
    X, Y, Z = rel.col[0].to_3d(), rel.col[1].to_3d(), rel.col[2].to_3d()
    p, y, r = rotator(Vector((X.x, -X.y, X.z)), Vector((-Y.x, Y.y, -Y.z)), Vector((Z.x, -Z.y, Z.z)))
    return (f"FTransform(FRotator({p:.2f}, {y:.2f}, {r:.2f}), FVector({t.x * 100:.2f}, {-t.y * 100:.2f}, {t.z * 100:.2f}))")


lines = ["// monke_island - generated by scripts/props/musket_tp_tracks.py from bean-musket-anim.blend, do not edit",
         f"// musket (socket grip_r) relative to hand_r, one transform per frame at {FPS} fps from the start of each clip", ""]
for kind, (f0, f1) in RANGES.items():
    lines.append(f"{kind}MusketTrack = {{")
    lines += [f"\t{relative(f)}," for f in range(f0, f1 + 1)]
    lines += ["};", ""]
lines.append(f"MusketTrackFrameRate = {FPS}.0f;")
lines.append("")
OUT.write_text("\n".join(lines), encoding="utf-8")
print("written", OUT, {k: v[1] - v[0] + 1 for k, v in RANGES.items()})
