"""Offline check of a T-334 pack (bolt-action rifle, sub-machine gun, bayonet musket), outside Unreal and outside
Blender: the manifest art/export/Weapons/<Weapon>/pack.json against its contract (scripts/props/<pack>/spec.py):
files and sha256, FBX units (UnitScaleFactor 100 = metres), every clip in both views with the contract's length and
events (TP = FP), the animation FBX count, the bones and sockets in the weapon base FBX and its skin clusters, the bean
bases, the statics, the textures listed by label (PNG sizes, colour spaces), fp-framing.json, the hand errors
(FP exact, TP within the bean's reach). Writes <pack>/<weapon>-clips.inl.txt (the FFirearmClip::Make table in the
format of scripts/character/pirate_weapon_clips.py; the new gestures need their EFirearmGesture value first).

  python scripts/props/period_arms_common/check_pack.py art/export/Weapons/BoltRifle [art/export/Weapons/Mitraillette ...]
Exit 1 when something is wrong.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import os
import struct
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
SPECS = {'BoltRifle': 'boltrifle_pack', 'Mitraillette': 'smg_pack', 'BayonetMusket': 'bayonet_musket_pack'}


def load_spec(tag):
    path = os.path.join(ROOT, 'scripts', 'props', SPECS[tag], 'spec.py')
    spec = importlib.util.spec_from_file_location(f'{SPECS[tag]}_spec_check', path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def fbx_unit(path):
    data = open(path, 'rb').read()
    i = data.find(b'UnitScaleFactor')
    if i < 0:
        return None
    j = data.find(b'D', data.find(b'Number', i))
    return struct.unpack('<d', data[j + 1:j + 9])[0]


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def png_size(path):
    with open(path, 'rb') as f:
        head = f.read(24)
    if head[:8] != b'\x89PNG\r\n\x1a\n':
        return None
    return struct.unpack('>II', head[16:24])


def clip_table(m, spec):
    by_view = {}
    for scene in m['scenes']:
        events = [(e['frame'] - scene['start'], e['name']) for e in scene['events']]
        by_view[(scene['view'], scene['clip'])] = (scene['end'] - scene['start'], scene['fps'], events)
    lines = [f"\t/** {m['format']} v{m['version']} ({m.get('pack')}): {len(by_view) // 2} gestures, generated by "
             f"scripts/props/period_arms_common/check_pack.py (new gestures: {', '.join(getattr(spec, 'NEW_GESTURES', ())) or 'none'}) */",
             f"\tinline void Add{m['weapon']}Clips(TArray<FFirearmClip>& Out)", "\t{"]
    for (view, clip), (frames, fps, events) in by_view.items():
        if view != 'TP':
            continue
        loop = 'true' if clip in spec.LOOPS else 'false'
        ev = ', '.join(f'{{ TEXT("{name}"), {frame} }}' for frame, name in events)
        lines.append(f"\t\tOut.Add(FFirearmClip::Make(EFirearmGesture::{clip}, {frames}, {fps}, {loop}, {{ {ev} }}));"
                     if ev else f"\t\tOut.Add(FFirearmClip::Make(EFirearmGesture::{clip}, {frames}, {fps}, {loop}, {{}}));")
    lines.append("\t}")
    return '\n'.join(lines) + '\n'


def check(pack):
    m = json.load(open(os.path.join(pack, 'pack.json'), encoding='utf-8'))
    tag = m['weapon']
    spec = load_spec(tag)
    errors, warnings = [], []
    report = {'pack': pack, 'weapon': tag, 'format': f"{m['format']} v{m['version']}", 'status': m.get('status'), 'fps': m['fps'],
              'units': {}, 'clips': {}, 'assets': len(m['assets'])}
    if m.get('status') != 'built':
        errors.append(f'status {m.get("status")} (the build writes "built")')
    if m['fps'] != spec.FPS:
        errors.append(f'fps {m["fps"]} (contract {spec.FPS})')
    sizes = 0
    for entry in m['assets']:
        path = os.path.join(pack, entry['path'])
        if not os.path.isfile(path):
            errors.append(f'missing {entry["path"]}')
            continue
        sizes += os.path.getsize(path)
        if not entry.get('sha256') or sha256(path) != entry['sha256']:
            errors.append(f'sha256 mismatch {entry["path"]}')
        if path.endswith('.fbx'):
            unit = fbx_unit(path)
            report['units'][str(unit)] = report['units'].get(str(unit), 0) + 1
    report['exports_mb'] = round(sizes / 1e6, 1)
    if set(report['units']) - {'100.0'}:
        errors.append(f'FBX units {report["units"]} (expected UnitScaleFactor 100 everywhere: metres)')
    scenes = {(s['view'], s['clip']): s for s in m['scenes']}
    for clip, frames in spec.CLIPS.items():
        for view in ('TP', 'FP'):
            if (view, clip) not in scenes:
                errors.append(f'clip {view} {clip} missing')
        tp, fp = scenes.get(('TP', clip)), scenes.get(('FP', clip))
        if not tp or not fp:
            continue
        if tp['end'] != frames or fp['end'] != frames:
            errors.append(f'clip {clip}: {tp["end"]}/{fp["end"]} frames (contract {frames})')
        a = sorted((e['frame'], e['name']) for e in tp['events'])
        b = sorted((e['frame'], e['name']) for e in fp['events'])
        want = sorted((e[0], e[1]) for e in spec.EVENTS.get(clip, []))
        if a != b:
            errors.append(f'clip {clip}: TP and FP events differ')
        if a != want:
            errors.append(f'clip {clip}: events {a} (contract {want})')
        report['clips'][clip] = {'frames': frames, 'seconds': round(frames / spec.FPS, 3), 'loop': clip in spec.LOOPS, 'events': a,
                                 'tp_hand_error_m': {k: round(v, 3) for k, v in tp['qa']['hand_error_max_m'].items()},
                                 'tp_arm_stretch_max': round(tp['qa']['upperarm_scale_max'], 3)}
        if max(tp['qa']['hand_error_max_m'].values()) > 0.08:
            warnings.append(f'TP {clip}: a hand misses its target by {max(tp["qa"]["hand_error_max_m"].values()):.3f} m (short bean arms)')
        if max(fp['qa']['hand_error_max_m'].values()) > 0.002:
            errors.append(f'FP {clip}: hand error {fp["qa"]["hand_error_max_m"]}')
    anims = [a for a in m['assets'] if a['type'] == 'animation']
    bean = sum(1 for a in anims if a['skeleton_group'] == 'Bean')
    report['animation_fbx'] = {'bean': bean, 'weapon': len(anims) - bean}
    if bean != len(spec.CLIPS) * 2 or len(anims) - bean != len(spec.CLIPS) * 2:
        errors.append(f'animation FBX: {bean} bean / {len(anims) - bean} weapon (expected {len(spec.CLIPS) * 2} each)')
    for a in anims:
        want = f'A_Bean_{tag}_{a["view"]}_{a["clip"]}' if a['skeleton_group'] == 'Bean' else f'A_{tag}_{a["view"]}_{a["clip"]}'
        if os.path.splitext(os.path.basename(a['path']))[0] != want:
            errors.append(f'animation name {a["path"]} (expected {want})')
    base = next((a for a in m['assets'] if a['type'] == 'skeletal_mesh' and a['skeleton_group'] == tag), None)
    if base:
        data = open(os.path.join(pack, base['path']), 'rb').read()
        want_bones = list(spec.BONES) + list(getattr(spec, 'MARKERS', {})) + ['socket_' + s for s in spec.SOCKETS] + m['weapon_contract']['bones']
        missing = [b for b in want_bones if data.find(b.encode()) < 0]
        if missing:
            errors.append(f'base FBX lacks bones {sorted(set(missing))}')
        clusters = data.count(b'Cluster')
        report['weapon_base'] = {'path': base['path'], 'bones': len(m['weapon_contract']['bones']), 'skin_clusters_in_fbx': clusters,
                                 'triangles': m['weapon_contract'].get('triangle_count'),
                                 'size_cm': [round(v * 100, 1) for v in m['weapon_contract']['bounds']['size']]}
        if clusters == 0:
            errors.append('weapon base FBX has no skin cluster')
    else:
        errors.append('no weapon base FBX')
    for view in ('TP', 'FP'):
        if not any(a['type'] == 'skeletal_mesh' and a['skeleton_group'] == 'Bean' and a.get('view') == view for a in m['assets']):
            errors.append(f'bean base {view} missing')
    st = {os.path.splitext(os.path.basename(a['path']))[0]: a for a in m['assets'] if a['type'] == 'static_mesh' and a['path'].endswith('.fbx')}
    for name in spec.STATICS:
        if name not in st:
            errors.append(f'static {name} missing')
        elif not os.path.isfile(os.path.join(pack, 'exports', 'Static', name + '.glb')):
            errors.append(f'static {name}: glb missing')
    pickups = [n for n, a in st.items() if a.get('view') == 'pickup']
    if pickups != [f'SM_Bean_{tag}']:
        errors.append(f'pickup statics {pickups} (expected SM_Bean_{tag})')
    report['statics'] = {n: {'view': a.get('view'), 'size_m': a.get('size_m'), 'triangles': a.get('triangles'), 'collision': a.get('collision'),
                             'materials': a.get('material')} for n, a in st.items()}
    tex = {}
    for mat, data in (m.get('materials') or {}).items():
        if not data.get('textures'):
            continue
        tex[mat] = {}
        for label, cs in (('BaseColor', 'sRGB'), ('Normal', 'Non-Color'), ('ORM', 'Non-Color')):
            info = data['textures'].get(label)
            if not info:
                errors.append(f'{mat}: texture {label} missing')
                continue
            info = info if isinstance(info, dict) else {'path': info}
            path = os.path.join(pack, info['path'])
            got = png_size(path) if os.path.isfile(path) else None
            tex[mat][label] = {'path': info['path'], 'size': got, 'colorspace': info.get('colorspace')}
            if not got or got[0] != got[1] or got[0] & (got[0] - 1):
                errors.append(f'{mat} {label}: size {got} (a square power of two expected)')
            if info.get('colorspace') and info.get('colorspace') != cs:
                errors.append(f'{mat} {label}: colour space {info.get("colorspace")} (expected {cs})')
    report['textures'] = tex
    if not tex:
        errors.append('no baked material in manifest.materials')
    framing_file = os.path.join(pack, 'fp-framing.json')
    if not os.path.isfile(framing_file):
        errors.append('fp-framing.json missing')
    else:
        fr = json.load(open(framing_file, encoding='utf-8'))
        report['fp_framing'] = {k: fr.get(k) for k in ('hip_grip_location_cm', 'hip_rotation_pyr_deg', 'aim_muzzle_location_cm',
                                                       'aim_rotation_pyr_deg', 'aim_field_of_view_deg', 'align_bone', 'grip_socket')}
        if 'hip_grip_location_cm' not in fr:
            errors.append('fp-framing.json: no hip framing')
        if 'AimIdle' in spec.CLIPS and 'aim_muzzle_location_cm' not in fr:
            errors.append('fp-framing.json: no aim framing although the pack has AimIdle')
    out = os.path.join(pack, f'{tag.lower()}-clips.inl.txt')
    with open(out, 'w', encoding='utf-8', newline='') as f:
        f.write(clip_table(m, spec).replace('\n', '\r\n'))
    report['errors'], report['warnings'] = errors, warnings
    print(json.dumps(report, indent=1, ensure_ascii=False))
    print(f'{tag}: ' + ('CHECK OK' if not errors else 'CHECK FAILED'))
    return not errors


if __name__ == '__main__':
    packs = sys.argv[1:] or [os.path.join(ROOT, 'art', 'export', 'Weapons', t) for t in SPECS]
    ok = True
    for p in packs:
        if os.path.isfile(os.path.join(p, 'pack.json')):
            ok = check(p) and ok
        else:
            print(f'{p}: no pack.json')
            ok = False
    sys.exit(0 if ok else 1)
