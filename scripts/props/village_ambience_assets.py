"""Small assets of the village ambience (AVillageAmbienceActor): a butterfly and a firefly, written without Blender
(Blender runs on the second PC since 2026-10-03; these are two-quad and icosphere meshes).

Usage: python scripts/props/village_ambience_assets.py
Output: art/export/Props/Village/Ambience/
  SM_Village_Butterfly.obj   two wings (quads with a slight dihedral) along +-Y, body along +X (head), in cm;
                             the actor flaps them by squeezing Y
  T_Village_Butterfly_D.png  RGBA wing pattern (monarch-like orange, black veins and margins, white dots; alpha
                             cut-out), drawn procedurally
  SM_Village_Firefly.obj     icosphere of 1.5 cm radius (emissive material in Unreal)
"""
import math
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "art" / "export" / "Props" / "Village" / "Ambience"

SPAN = 7.0        # half wing span (cm)
LENGTH = 4.2      # half length of the wings along the body (cm)
DIHEDRAL = 0.16   # wing tips rise this much per cm of span
TEX_W, TEX_H = 256, 160


def write_obj(path, name, verts, uvs, normals, faces):
    lines = [f"# {name}, generated by scripts/props/village_ambience_assets.py (units: cm)", f"o {name}"]
    lines += [f"v {x:.4f} {y:.4f} {z:.4f}" for x, y, z in verts]
    lines += [f"vt {u:.5f} {v:.5f}" for u, v in uvs]
    lines += [f"vn {x:.5f} {y:.5f} {z:.5f}" for x, y, z in normals]
    lines += ["f " + " ".join(f"{a + 1}/{b + 1}/{c + 1}" for a, b, c in f) for f in faces]
    path.write_text("\n".join(lines) + "\n", encoding="ascii")


def butterfly_mesh():
    """Two wings, each a strip of quads from the body line (y = 0) to the tip, both faces kept by a two-sided
    material. X = forward (head), Y = span, Z = up; UV u along the span, v along the body (head at v = 0)."""
    verts, uvs, normals, faces = [], [], [], []
    for side in (1.0, -1.0):
        for x in (-LENGTH, LENGTH):
            for y in (0.0, SPAN):
                verts.append((x, side * y, DIHEDRAL * y))
                uvs.append((0.5 + side * y / (2.0 * SPAN), 1.0 - (x + LENGTH) / (2.0 * LENGTH)))
        n = np.array([0.0, -side * DIHEDRAL, 1.0])
        n /= np.linalg.norm(n)
        normals.append(tuple(n))
        b = len(verts) - 4
        ni = len(normals) - 1
        # corners: (tail, body) (tail, tip) (head, body) (head, tip); upward winding for both sides
        quad = [b, b + 2, b + 3, b + 1] if side > 0 else [b, b + 1, b + 3, b + 2]
        faces.append([(quad[0], quad[0], ni), (quad[1], quad[1], ni), (quad[2], quad[2], ni)])
        faces.append([(quad[0], quad[0], ni), (quad[2], quad[2], ni), (quad[3], quad[3], ni)])
    return verts, uvs, normals, faces


def butterfly_texture(path):
    """Monarch-like wings in UV space: u = span (0.5 = body), v = length (0 = head)."""
    s = 4
    W, H = TEX_W * s, TEX_H * s
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    orange, black, white = (232, 122, 26, 255), (24, 18, 14, 255), (244, 240, 228, 255)

    def px(u, v):
        return (u * W, v * H)

    for side in (1, -1):
        def U(t):
            return 0.5 + side * t * 0.5          # t = 0 at the body, 1 at the tip

        fore = [px(U(0.02), 0.08), px(U(0.55), 0.02), px(U(0.98), 0.10), px(U(0.92), 0.42), px(U(0.45), 0.58),
                px(U(0.02), 0.50)]
        hind = [px(U(0.02), 0.50), px(U(0.48), 0.54), px(U(0.80), 0.70), px(U(0.70), 0.95), px(U(0.30), 0.98),
                px(U(0.02), 0.80)]
        for poly in (fore, hind):
            d.polygon(poly, fill=black)
            # inner orange cells, inset from the black margin
            c = np.mean(np.array(poly), axis=0)
            inner = [tuple(c + (np.array(p) - c) * 0.80) for p in poly]
            d.polygon(inner, fill=orange)
            # veins from the wing root
            root = np.array(px(U(0.03), 0.52))
            for p in poly[1:-1]:
                q = root + (np.array(p) - root) * 0.82
                d.line([tuple(root), tuple(q)], fill=black, width=int(0.010 * W))
        # white dots in the black margin
        for t, v in ((0.62, 0.05), (0.75, 0.07), (0.87, 0.10), (0.93, 0.25), (0.90, 0.36), (0.74, 0.86), (0.55, 0.94),
                     (0.38, 0.95)):
            x, y = px(U(t), v)
            r = 0.012 * W
            d.ellipse([x - r, y - r, x + r, y + r], fill=white)
    # body
    d.ellipse([0.5 * W - 0.018 * W, 0.04 * H, 0.5 * W + 0.018 * W, 0.96 * H], fill=black)
    img = img.filter(ImageFilter.GaussianBlur(radius=s * 0.35)).resize((TEX_W, TEX_H), Image.LANCZOS)
    a = np.asarray(img).copy()
    a[..., 3] = np.where(a[..., 3] > 110, 255, 0)      # hard cut-out for the masked material
    Image.fromarray(a, "RGBA").save(path)


def icosphere(radius, subdiv=1):
    t = (1.0 + math.sqrt(5.0)) / 2.0
    v = [(-1, t, 0), (1, t, 0), (-1, -t, 0), (1, -t, 0), (0, -1, t), (0, 1, t), (0, -1, -t), (0, 1, -t),
         (t, 0, -1), (t, 0, 1), (-t, 0, -1), (-t, 0, 1)]
    f = [(0, 11, 5), (0, 5, 1), (0, 1, 7), (0, 7, 10), (0, 10, 11), (1, 5, 9), (5, 11, 4), (11, 10, 2), (10, 7, 6),
         (7, 1, 8), (3, 9, 4), (3, 4, 2), (3, 2, 6), (3, 6, 8), (3, 8, 9), (4, 9, 5), (2, 4, 11), (6, 2, 10),
         (8, 6, 7), (9, 8, 1)]
    verts = [np.array(p, float) / np.linalg.norm(p) for p in v]
    for _ in range(subdiv):
        cache, nf = {}, []

        def mid(a, b):
            key = (min(a, b), max(a, b))
            if key not in cache:
                m = verts[a] + verts[b]
                verts.append(m / np.linalg.norm(m))
                cache[key] = len(verts) - 1
            return cache[key]
        for a, b, c in f:
            ab, bc, ca = mid(a, b), mid(b, c), mid(c, a)
            nf += [(a, ab, ca), (b, bc, ab), (c, ca, bc), (ab, bc, ca)]
        f = nf
    out_v = [tuple(p * radius) for p in verts]
    out_n = [tuple(p) for p in verts]
    out_uv = [(0.5 + math.atan2(p[1], p[0]) / (2 * math.pi), 0.5 - math.asin(max(-1.0, min(1.0, p[2]))) / math.pi)
              for p in verts]
    faces = [[(a, a, a), (b, b, b), (c, c, c)] for a, b, c in f]
    return out_v, out_uv, out_n, faces


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    write_obj(OUT / "SM_Village_Butterfly.obj", "SM_Village_Butterfly", *butterfly_mesh())
    butterfly_texture(OUT / "T_Village_Butterfly_D.png")
    write_obj(OUT / "SM_Village_Firefly.obj", "SM_Village_Firefly", *icosphere(1.5, 1))
    for f in sorted(OUT.iterdir()):
        print(f"  {f.relative_to(ROOT)} ({f.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
