"""Offline check of a long arm pack (T-250), outside Unreal and outside Blender, with the logic of
scripts/character/import_pirate_weapons.py --check (files, sha256, FBX units) plus what the integrator needs to trust
the pack: every clip in both views, the events at the expected frames, the bones and sockets in the base FBX, the
textures listed by label, the reload duration. Writes <pack>/<weapon>-clips.inl.txt, the FFirearmClip::Make table of
the pack in the format of scripts/character/pirate_weapon_clips.py (to paste into PirateWeaponClips.inl once
EFirearmGesture has a Discard value).

  python scripts/props/longarm_common/check.py build/packs/bean-blunderbuss-anim [build/packs/bean-rifle-anim ...]
Exit 1 when something is wrong.
"""
from __future__ import annotations

import hashlib
import json
import os
import struct
import sys

MUSKET_GESTURES = ['Equip', 'Idle', 'Walk', 'Sprint', 'AimIn', 'AimIdle', 'AimOut', 'HalfCock', 'PrimePan', 'CloseFrizzen',
                   'GroundReload', 'Powder', 'BallAndPatch', 'DrawRamrod', 'TurnRamrod', 'RamrodStroke', 'ReturnRamrod', 'Cock',
                   'Present', 'Fire', 'Recoil', 'Hold', 'ReturnToPort', 'Holster']
EXTRA_GESTURES = ['Inspect', 'Discard', 'AimFire']
# EFirearmGesture values of Weapons/FirearmRules.h (Discard is NOT there yet: the integrator adds it)
ENUM = {'Equip', 'Idle', 'Walk', 'Sprint', 'AimIn', 'AimIdle', 'AimOut', 'Fire', 'AimFire', 'Reload', 'DryFire', 'Inspect', 'Holster',
        'Cock', 'ReloadStart', 'ReloadInsert', 'ReloadEnd', 'ReloadEmpty', 'GroundReload', 'HalfCock', 'PrimePan', 'CloseFrizzen',
        'Powder', 'BallAndPatch', 'DrawRamrod', 'TurnRamrod', 'RamrodStroke', 'ReturnRamrod', 'Present', 'Recoil', 'Hold', 'ReturnToPort'}
LOOPS = {'Idle', 'Walk', 'Sprint', 'AimIdle', 'Hold'}
REQUIRED_BONES = ['root', 'hammer', 'frizzen', 'trigger', 'ramrod', 'cartridge', 'socket_grip_r', 'socket_grip_l', 'socket_barrel',
                  'socket_muzzle', 'socket_pan', 'socket_butt', 'socket_sling', 'socket_ramrod_tip', 'socket_ramrod_end', 'socket_flint',
                  'socket_sight_rear', 'socket_sight_front']
RELOAD_EVENTS = ['HalfCockStart', 'PanPrime', 'FrizzenClose', 'StockLowered', 'PowderCharge', 'BallAndPatch', 'RamrodDraw', 'RamrodTurn',
                 'RamrodStroke', 'RamrodStroke', 'RamrodReturn', 'FullCockEnd']


def fbx_unit(path):
    data = open(path, 'rb').read()
    i = data.find(b'UnitScaleFactor')
    if i < 0:
        return None
    j = data.find(b'D', data.find(b'Number', i))
    return struct.unpack('<d', data[j + 1:j + 9])[0]


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def png_size(path):
    with open(path, 'rb') as f:
        head = f.read(24)
    if head[:8] != b'\x89PNG\r\n\x1a\n':
        return None
    return struct.unpack('>II', head[16:24])


def clip_table(weapon, manifest):
    by_view = {}
    for scene in manifest['scenes']:
        events = [(e['frame'] - scene['start'], e['name']) for e in scene['events']]
        by_view[(scene['view'], scene['clip'])] = (scene['end'] - scene['start'], scene['fps'], events)
    lines = [f"\t/** {manifest['format']} v{manifest['version']} ({manifest.get('pack')}): {len(by_view) // 2} gestures, generated by "
             f"scripts/props/longarm_common/check.py */", f"\tinline void Add{weapon}Clips(TArray<FFirearmClip>& Out)", "\t{"]
    for (view, clip), (frames, fps, events) in by_view.items():
        if view != 'TP':
            continue
        loop = 'true' if clip in LOOPS else 'false'
        ev = ', '.join(f'{{ TEXT("{name}"), {frame} }}' for frame, name in events)
        note = '' if clip in ENUM else '  // EFirearmGesture::Discard: add it to Weapons/FirearmRules.h first'
        lines.append(f"\t\tOut.Add(FFirearmClip::Make(EFirearmGesture::{clip}, {frames}, {fps}, {loop}, {{ {ev} }}));{note}"
                     if ev else f"\t\tOut.Add(FFirearmClip::Make(EFirearmGesture::{clip}, {frames}, {fps}, {loop}, {{}}));{note}")
    lines.append("\t}")
    return '\n'.join(lines) + '\n'


def check(pack):
    manifest_name = next((n for n in os.listdir(pack) if n.endswith('-manifest.json')), None)
    if not manifest_name:
        print(f'{pack}: no manifest')
        return False
    m = json.load(open(os.path.join(pack, manifest_name), encoding='utf-8'))
    weapon = m['weapon']
    errors, warnings = [], []
    report = {'pack': pack, 'manifest': manifest_name, 'weapon': weapon, 'format': f"{m['format']} v{m['version']}", 'fps': m['fps'],
              'units': {}, 'clips': {}, 'assets': len(m['assets'])}
    if m['fps'] != 24:
        errors.append(f'fps {m["fps"]} (expected 24)')
    for entry in m['assets']:
        path = os.path.join(pack, entry['path'])
        if not os.path.isfile(path):
            errors.append(f'missing {entry["path"]}')
            continue
        if entry.get('sha256') and sha256(path) != entry['sha256']:
            errors.append(f'sha256 mismatch {entry["path"]}')
        if path.endswith('.fbx'):
            unit = fbx_unit(path)
            report['units'][str(unit)] = report['units'].get(str(unit), 0) + 1
    if set(report['units']) - {'100.0'}:
        errors.append(f'FBX units {report["units"]} (expected UnitScaleFactor 100 everywhere: metres)')
    # clips: every gesture in both views, same length and events in TP and FP
    scenes = {(s['view'], s['clip']): s for s in m['scenes']}
    expected = MUSKET_GESTURES + EXTRA_GESTURES
    for clip in expected:
        for view in ('TP', 'FP'):
            if (view, clip) not in scenes:
                errors.append(f'clip {view} {clip} missing')
        tp, fp = scenes.get(('TP', clip)), scenes.get(('FP', clip))
        if tp and fp:
            if (tp['end'], sorted((e['frame'], e['name']) for e in tp['events'])) != (fp['end'], sorted((e['frame'], e['name']) for e in fp['events'])):
                errors.append(f'clip {clip}: TP and FP differ (length or events)')
            report['clips'][clip] = {'frames': tp['end'], 'seconds': round(tp['end'] / m['fps'], 3),
                                     'events': [(e['frame'], e['name']) for e in tp['events']]}
    anims = [a for a in m['assets'] if a['type'] == 'animation']
    bean = sum(1 for a in anims if a['skeleton_group'] == 'Bean')
    report['animation_fbx'] = {'bean': bean, 'weapon': len(anims) - bean}
    if bean != len(expected) * 2 or len(anims) - bean != len(expected) * 2:
        errors.append(f'animation FBX: {bean} bean / {len(anims) - bean} weapon (expected {len(expected) * 2} each)')
    # reload: duration and the event order
    rs = m['reload_sequence']
    report['reload'] = {'frames': rs['end_frame'], 'seconds': rs['duration_s'], 'windows': rs['windows_frames'],
                        'events': [(e['frame'], e['name']) for e in rs['events']]}
    names = [e['name'] for e in rs['events']]
    for name in RELOAD_EVENTS:
        if names.count(name) < RELOAD_EVENTS.count(name):
            errors.append(f'reload event {name} missing')
    frames = [e['frame'] for e in rs['events']]
    if frames != sorted(frames):
        errors.append('reload events not sorted')
    if rs['end_frame'] != scenes[('TP', 'GroundReload')]['end'] if ('TP', 'GroundReload') in scenes else True:
        errors.append('reload_sequence.end_frame differs from the GroundReload clip')
    # shot and discard events
    for clip in ('Fire', 'AimFire'):
        ev = {(e['frame'], e['name']) for e in scenes.get(('TP', clip), {'events': []})['events']}
        for need in ((5, 'Trigger'), (8, 'Shot'), (8, 'MuzzleFlash')):
            if need not in ev:
                errors.append(f'{clip}: event {need} missing')
    ev = {e['name']: e['frame'] for e in scenes.get(('TP', 'Discard'), {'events': []})['events']}
    if 'Empty' not in ev or 'Release' not in ev or not ev['Empty'] < ev['Release']:
        errors.append(f'Discard: events Empty / Release wrong: {ev}')
    report['discard'] = m.get('discard')
    # weapon base: bones and sockets present in the FBX
    base = next((a for a in m['assets'] if a['type'] == 'skeletal_mesh' and a['view'] == 'shared'), None)
    if base:
        data = open(os.path.join(pack, base['path']), 'rb').read()
        missing = [b for b in REQUIRED_BONES + ['socket_' + s for s in []] if data.find(b.encode()) < 0]
        if missing:
            errors.append(f'base FBX lacks bones {missing}')
        contract = m['weapon_contract']
        missing = [b for b in contract['bones'] if data.find(b.encode()) < 0]
        if missing:
            errors.append(f'base FBX lacks contract bones {missing}')
        report['weapon_bones'] = contract['bones']
        report['weapon_size_cm'] = [round(v * 100, 1) for v in contract['bounds']['size']]
    else:
        errors.append('no weapon base FBX')
    # textures by label
    mats = m.get('materials', {})
    tex_report = {}
    for mat_name, mat in mats.items():
        if not mat.get('textures'):
            continue
        tex_report[mat_name] = {}
        for label, info in mat['textures'].items():
            path = os.path.join(pack, info['path'])
            if not os.path.isfile(path):
                errors.append(f'texture {info["path"]} missing')
                continue
            tex_report[mat_name][label] = {'path': info['path'], 'size': png_size(path), 'colorspace': info.get('colorspace')}
        for label, cs in (('BaseColor', 'sRGB'), ('Normal', 'Non-Color'), ('ORM', 'Non-Color')):
            if label not in mat['textures']:
                errors.append(f'{mat_name}: texture {label} missing')
            elif mat['textures'][label].get('colorspace') != cs:
                errors.append(f'{mat_name}: texture {label} colorspace {mat["textures"][label].get("colorspace")} (expected {cs})')
    weapon_mat = f'M_Bean_Pirate{weapon}'
    if weapon_mat not in tex_report:
        errors.append(f'material {weapon_mat} with its textures missing from manifest.materials')
    elif any(v['size'] != (2048, 2048) for v in tex_report[weapon_mat].values()):
        warnings.append(f'{weapon_mat}: textures not 2048')
    report['textures'] = tex_report
    report['fp_framing'] = {k: m['fp_framing'][k] for k in ('hip_grip_location_cm', 'hip_rotation_pyr_deg', 'aim_muzzle_location_cm',
                                                            'aim_rotation_pyr_deg', 'aim_field_of_view_deg') if k in m['fp_framing']}
    if not os.path.isfile(os.path.join(pack, 'fp-framing.json')):
        errors.append('fp-framing.json missing')
    table = clip_table(weapon, m)
    with open(os.path.join(pack, f'{weapon.lower()}-clips.inl.txt'), 'w', encoding='utf-8', newline='') as f:
        f.write(table.replace('\n', '\r\n'))
    report['errors'], report['warnings'] = errors, warnings
    print(json.dumps(report, indent=1, ensure_ascii=False))
    print(f'{weapon}: ' + ('CHECK OK' if not errors else 'CHECK FAILED'))
    return not errors


if __name__ == '__main__':
    packs = sys.argv[1:] or [os.path.join('build', 'packs', 'bean-blunderbuss-anim'), os.path.join('build', 'packs', 'bean-rifle-anim')]
    ok = all([check(p) for p in packs])
    sys.exit(0 if ok else 1)
