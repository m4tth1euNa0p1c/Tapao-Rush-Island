"""T-213: LODs of the seven French bean uniforms (84 000 to 97 000 triangles each, manifest: "réduction automatique Unreal
50 % puis 25 %"): three LODs generated by the engine's reduction, then saved. Seven soldiers in a fort otherwise draw
some 630 000 triangles at every distance.
Runs in the editor: scripts/editor/lead_session_t186.py, action "beanfrlods".
Result: monke_island/Saved/T213/beanfr-lods.json
"""
import datetime as dt
import json
import sys
from pathlib import Path

import unreal as ue

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts/props"))
import minka_doors_ue as kitlib  # noqa: E402

OUT = ROOT / "monke_island/Saved/T213"
MESHES = "/Game/MonkeIsland/Characters/BeanFR/Meshes"
SKINS = ("CFM_Fusilier", "Fusilier_1767", "Fusilier_Bicorne", "Chasseur_Shako", "Grenadier", "Sergent", "Officier_Marine")
LOD_COUNT = 3


def main():
    kitlib.check_lock()
    tool = ue.get_editor_subsystem(ue.SkeletalMeshEditorSubsystem)
    report = {}
    for name in SKINS:
        mesh = kitlib.load(f"{MESHES}/SK_BeanFR_{name}")
        assert mesh, name
        before = tool.get_lod_count(mesh)
        if before < LOD_COUNT:
            assert tool.regenerate_lod(mesh, LOD_COUNT, False, False), f"{name}: LODs not generated"
        kitlib.save(mesh)
        report[name] = {"before": before, "after": tool.get_lod_count(mesh)}
    report["finished_at"] = dt.datetime.now(dt.timezone.utc).isoformat()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "beanfr-lods.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    ue.log("T213_BEANFR_LODS_DONE")


if __name__ == "__main__":
    main()
