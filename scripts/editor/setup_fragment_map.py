def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("fragment")
    ap.add_argument("--part", required=True, choices=["material", "tile", "assets", "vegetation", "maps", "core", "level", "wire"])
    ap.add_argument("--tile", type=int, default=0)
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()

    p = frag_paths(args.fragment)
    geo = json.loads((REF / "fragments" / args.fragment / "georef.json").read_text(encoding="utf-8"))
    frags = json.loads((REF / "fragments/fragments.json").read_text(encoding="utf-8"))["fragments"]
    frag = next(f for f in frags if f["id"] == args.fragment)
    raw = p["raw"]
    pdata = {k: (str(v) if isinstance(v, Path) else v) for k, v in p.items()}
    pdata["masks_file"] = str(raw / f"T_{p['short']}_Masks.png")
    pdata["water_file"] = str(raw / f"SM_{p['short']}_Water.obj")
    pdata["horizon_file"] = str(raw / f"SM_{args.fragment}_Horizon.obj")
    tiles = [(t["name"], str(ROOT / t["file"])) for t in geo["mesh"]["tiles"]]
    veg_path = REF / "fragments" / args.fragment / "vegetation.json"
    veg = json.loads(veg_path.read_text(encoding="utf-8")) if veg_path.exists() else {"blocks": []}

    script = HEADER.replace("__P__", repr(pdata))
    if args.part == "material":
        script += MATERIAL
    elif args.part == "tile":
        script += TILE.replace("__TILE__", repr(list(tiles[args.tile])))
    elif args.part == "assets":
        script += ASSETS
    elif args.part == "vegetation":
        script += VEGETATION.replace("__BLOCKS__", repr([[b["name"], str(ROOT / b["file"]), b["rows"]]
                                                         for b in veg["blocks"]]))
    elif args.part == "maps":
        script += MAPS
    elif args.part == "core":
        script += CORE
    elif args.part == "level":
        a = frag["arrival"]
        # Fallback PlayerStart 15 m inland from the beach targeted by the boat (FRG_01: the beach is a 30 m wide islet), facing inland (z from a trace)
        yaw = math.radians(a["yaw_deg"])
        tx, ty = a["target_cm"][0] + 1500.0 * math.cos(yaw), a["target_cm"][1] + 1500.0 * math.sin(yaw)
        pstart = [round(tx, 1), round(ty, 1), 300.0, round(a["yaw_deg"], 2)]
        script += (LEVEL.replace("__TILES__", repr([t[0] for t in tiles]))
                   .replace("__BLOCKS__", repr([[b["name"], b["physics"], b["bounds_cm"]] for b in veg["blocks"]]))
                   .replace("__ARRIVAL__", repr([a["location_cm"][0], a["location_cm"][1], a["yaw_deg"]]))
                   .replace("__PSTART__", repr(pstart)))
    else:
        script += WIRE

    if args.out:
        args.out.write_text(script, encoding="utf-8")
    else:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stdout.write(script)


if __name__ == "__main__":
    main()
