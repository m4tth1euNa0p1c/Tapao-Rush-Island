"""Generate the editor scripts that build the map of one Tuamotu fragment (T-089, lot L3).

The Unreal MCP has no free Python: its ProgrammaticToolset runs a sandboxed script (json/math/re/time only, no
file access) that chains MCP tool calls. This generator reads the offline outputs of the fragment pipeline and
writes such scripts, data inlined. Pass the content of the output to ProgrammaticToolset.execute_tool_script.

    python scripts/editor/setup_fragment_map.py FRG_Raraka_01 --part <part> [--tile N] [--out out.py]

Parts, in order (each one is idempotent: an existing asset or actor is reused, never duplicated):
- material   : M_Horizon_Atoll (unlit master, recipe of docs/features/fragments-tuamotu.md, section Horizon).
- tile --tile N : imports terrain tile N (0-based, order of georef.json): OBJ in cm, convex hull removed,
               CTF_UseComplexAsSimple, Nanite with 100 % fallback, MI_<FRG>_Terrain. One tile per call (RAM).
- assets     : mask texture (linear, TC_Masks), MI_<FRG>_Terrain (M_Terrain_Atoll, Masks = fragment masks),
               water plane (M_Water_Lagoon, no collision), horizon mesh (no collision, MI_Horizon_Raraka).
- vegetation : DataTables of fragment_vegetation.py (GameplayTagTableRow) in <folder>/Vegetation.
- maps       : creates LI_ExpeditionCore and L_Frag_<...> by duplicating /Engine/Maps/Templates/Template_Default
               (no "new level" tool in the MCP), then opens LI_ExpeditionCore. Refuses when a PIE runs or when
               the open level has unsaved changes (they may belong to another session).
- core       : needs LI_ExpeditionCore open. Removes Floor, SkySphere and PlayerStart of the template, sets the
               sky like Lvl_Raraka (sun, sky light, height fog), adds the shared systems with the rules of
               Lvl_Raraka: DayNightCycle, WindStorm, FloodSimulation, CoconutFallDirector (Core/Systems),
               CampSpawner, LootScatterSpawner, GalleonSpawner, TikiDirector (Core/Content).
- level      : needs L_Frag_<...> open in the editor. Removes the sky and floor of the template (they come from
               LI_ExpeditionCore), sets the GameMode Override BP_IslandGameMode, Places terrain tiles, water (tag IslandWaterSurface),
               horizon (no shadow, no collision), arrival point, fallback PlayerStart, PCG blocks
               (PCG_Raraka_VegHard / VegSoft with DataTable param), BP_VillageSpawner, LI_ExpeditionCore.
- wire       : DA_Island_<..>.Map -> L_Frag map.

Paths: assets in /Game/MonkeIsland/Map/Fragments/<FRG>/, maps in /Game/MonkeIsland/Maps/Fragments/.
Same world frame as Lvl_Raraka (offset 0): everything is placed at the origin or at the json coordinates.
"""
